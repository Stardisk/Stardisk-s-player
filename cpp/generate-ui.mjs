// Build-time only. Copy exact geometry, fonts, captions and menu order from
// the versioned twinBASIC forms; no designer or parser ships in the player.
import fs from 'node:fs';
const quote=s=>'L'+JSON.stringify(s??'');
let ids=[], controls=[], menus=[], topMenus=[], index=100;
const ident=s=>s.replace(/[^A-Za-z0-9_]/g,'_');
const special={'Потоки':'Streams','Добавитьпоток':'AddStream'};
const id=(mode,name)=>`${mode}_${special[name]||ident(name)}`;
for(const mode of ['main','compact']) {
 const form=JSON.parse(fs.readFileSync(new URL(`../twinbasic/source/Sources/${mode}.frm.tbform`,import.meta.url)))[0];
 function visit(o,ox=0,oy=0){
  if(o._className==='Menu')return;
  if(o.Name!==mode&&o._className!=='Timer'&&o._className!=='Shape'&&o.Name!=='Label1' || o._className==='Label'&&mode==='main'){
   const key=id(mode,o.Name); ids.push(`${key} = ${index++}`);
   let kind={Label:0,CommandButton:1,CheckBox:2,Frame:3,TextBox:4,HScrollBar:5,Slider:6,DriveListBox:7,DirListBox:8,FileListBox:9,PictureBox:10}[o._className];
   if(kind!==undefined)controls.push(`{${key},${mode==='compact'?1:0},${kind},${ox+(o.Left||0)},${oy+(o.Top||0)},${o.Width||1},${o.Height||1},${quote(o.Caption||o.Text)},${quote(o.FontName||'MS Sans Serif')},${Math.round((o.FontSize||8.25)*100)},${typeof o.Alignment==='number'?o.Alignment:o.Alignment==='vbRightJustify'?1:o.Alignment==='vbCenter'?2:0},${o.AutoSize?1:0},${o.BackColor??-2147483633},${o.ForeColor??-2147483630},${o.TabIndex??-1},${quote(o.ToolTipText||'')}}`);
  }
  if(o._className!=='PictureBox')for(const c of o._children||[])visit(c,ox+(o.Name===mode?0:o.Left||0),oy+(o.Name===mode?0:o.Top||0));
 }
 visit(form);
 if(mode==='main') {
  // twinBASIC serializes menu children in reverse display order.
  for(const top of form._children.filter(x=>x._className==='Menu').reverse()){
   let items=[];
   for(const c of [...(top._children||[])].reverse()){if(c.Name==='mnuStreamSeparator'||c.Name==='mnuSavedStream')continue; if(c.Caption==='-'){items.push('{0,L"-",0}');continue;} let key=id('menu',c.Name);ids.push(`${key} = ${index++}`);let cap=c.Caption; if(c.Shortcut)cap+='\t'+({'^L':'Ctrl+L','^F':'Ctrl+F','^E':'Ctrl+E','^X':'Ctrl+X','{DEL}':'Del','{F2}':'F2'}[c.Shortcut]||'');items.push(`{${key},${quote(cap)},0}`);}
   if(top.Name==='mnuSep0') {
    items.splice(1,0,`{menu_mnuShowTaskbarProgress,${quote('Показывать прогресс воспроизведения на кнопке в панели задач')},0}`);
   }
   const key=id('popup',top.Name);menus.push(`static const MenuItem ${key}[] = {${items.join(',')}};`);
   topMenus.push(`{${quote(top.Caption)},${key},sizeof(${key})/sizeof(MenuItem),${top.Name==='Потоки'?'true':'false'}}`);
  }
 }
}
ids.push(`menu_mnuShowTaskbarProgress = ${index++}`);
const generated = '// Generated by generate-ui.mjs from the current twinBASIC forms.\n#pragma once\nenum ControlId {\n'+ids.join(',\n')+',\n menu_streamBase = 1000\n};\nstruct ControlDef { int id,compact,kind,x,y,w,h; const wchar_t* text; const wchar_t* font; int points100,align,autosize; LONG back,fore; int tab; const wchar_t* tip; };\nstatic const ControlDef controlDefs[] = {\n'+controls.join(',\n')+'\n};\nstruct MenuItem { int id; const wchar_t* text; int flags; };\n'+menus.join('\n')+'\nstruct MenuDef { const wchar_t* caption; const MenuItem* items; int count; bool streams; };\nstatic const MenuDef menuDefs[] = {\n'+topMenus.join(',\n')+'\n};\n';
const output = new URL('src/ui.generated.h', import.meta.url);
if (process.argv.includes('--check')) {
 const current = fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n');
 if (current !== generated) { console.error('ui.generated.h is out of date. Run node cpp/generate-ui.mjs.'); process.exit(1); }
 console.log('ui.generated.h matches the twinBASIC forms.');
} else { fs.writeFileSync(output, generated); }
console.log(`Generated ${controls.length} controls`);
